// Twelve included packs; the interface counts the bundled rows directly.
export const CATEGORIES = CATEGORY_ROWS.filter((r) => r[0] !== "ideas");
export function categories(language: Language) {
  const i = langs.indexOf(language);
  return CATEGORIES.map((r) => ({
    id: r[0],
    name: r[1 + i]!,
    description: r[6 + i]!,
    clue: r[11],
    color: r[12],
    icon: r[13],
    count: content[r[0] as keyof typeof content].length,
    custom: false,
  }));
}
export function words(language: Language): Word[] {
  const i = langs.indexOf(language);
  return categories(language).flatMap((cat) =>
    content[cat.id as keyof typeof content].map((w) => ({
      id: w.id,
      text: w.values[i]!,
      category: cat.name,
      clue: cat.clue,
    })),
  );
}
export function categoryWords(id: string, language: Language): Word[] {
  const i = langs.indexOf(language);
  const cat = categories(language).find((c) => c.id === id);
  return cat
    ? content[id as keyof typeof content].map((w) => ({
        id: w.id,
        text: w.values[i]!,
        category: cat.name,
        clue: cat.clue,
      }))
    : [];
}
